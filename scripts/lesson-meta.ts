/**
 * Regenerate `src/course/lessonMeta.json`: **the day each lesson's file first appeared in this
 * repository**, read from git.
 *
 *   npx vite-node scripts/lesson-meta.ts            # refresh
 *   npx vite-node scripts/lesson-meta.ts --check    # fail if the committed file is stale
 *
 * Why: the feature map's time axis carries two kinds of event per feature — what the task group
 * did (document numbers, dated by `docMeta.json`) and **what this repository did** (the lesson
 * that teaches the feature, dated here). A feature with a five-year argument behind it and a
 * lesson written in one afternoon says something that neither date says alone, and the second
 * date is the only one this repository can be held to.
 *
 * `--diff-filter=A` without `--follow` on purpose: the question is when THIS file appeared, and
 * a lesson split out of another one in October is new in October — following the rename would
 * date it to the parent's birthday and quietly claim we had it all along.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { LESSONS } from '../src/course/lessons'

const ROOT = 'src/course'
const OUT = 'src/course/lessonMeta.json'

/** Every `.ts` under `src/course`, by basename — lesson files are named after their id. */
function index(dir: string, into: Map<string, string>): Map<string, string> {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name).replaceAll('\\', '/')
    if (statSync(path).isDirectory()) { index(path, into); continue }
    if (!name.endsWith('.ts')) continue
    into.set(name.slice(0, -3), path)
  }
  return into
}

const git = (args: string[]): string =>
  execFileSync('git', args, { encoding: 'utf8' }).trim().split('\n')[0] ?? ''

const files = index(ROOT, new Map())
const lessons: Record<string, { file: string; added: string; touched: string }> = {}
const orphans: string[] = []

for (const lesson of LESSONS) {
  const file = files.get(lesson.id)
  if (file === undefined) { orphans.push(lesson.id); continue }
  const added = git(['log', '--diff-filter=A', '--format=%as', '-1', '--', file])
  const touched = git(['log', '--format=%as', '-1', '--', file])
  if (added === '') { orphans.push(lesson.id); continue }
  lessons[lesson.id] = { file, added, touched }
}

const out = {
  comment: 'Generated by scripts/lesson-meta.ts from this repository\'s git history: the day each'
    + ' lesson file was added, and the day it was last touched. Do not edit by hand.',
  generated: new Date().toISOString().slice(0, 10),
  head: git(['rev-parse', '--short', 'HEAD']),
  /** Lessons whose file git does not date — a lesson defined inline, or one never committed. */
  orphans,
  lessons,
}
const text = `${JSON.stringify(out, null, 1)}\n`

if (process.argv.includes('--check')) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const strip = (s: string): string => s.replace(/"(generated|head)": "[^"]+",/g, '')
  if (strip(have) !== strip(text)) {
    console.error(`${OUT} is stale — run: npx vite-node scripts/lesson-meta.ts`)
    process.exit(1)
  }
  console.log(`${OUT}: up to date (${Object.keys(lessons).length} lessons)`)
} else {
  writeFileSync(OUT, text)
  console.log(`→ ${OUT}: ${Object.keys(lessons).length} lessons`
    + `${orphans.length > 0 ? `, ${orphans.length} undated (${orphans.join(', ')})` : ''}`)
}
