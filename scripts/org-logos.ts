/**
 * Regenerate `src/course/orgLogos.json`: **the real brand mark for every company the feature map
 * can name**, as a single SVG path plus its brand colour.
 *
 *   npx vite-node scripts/org-logos.ts            # refresh from the pinned simple-icons release
 *   npx vite-node scripts/org-logos.ts --check    # fail if the committed file is stale
 *
 * **Where they come from, and why this one.** simple-icons (CC0-1.0, pinned below) distributes
 * each brand as one 24×24 path with the brand's own hex colour. That is the shape this map needs:
 * a mark the size of a chip, embeddable inline so the standalone HTML report still works with no
 * network, and no image file to carry. Nothing is fetched at run time — the paths are committed.
 *
 * **What a logo is doing here.** Naming which companies' names are on a contribution is
 * identification, and the marks stay the property of their owners; they are not endorsements and
 * this repository claims nothing by them. That is also why nothing is recoloured or redrawn: each
 * mark is used whole, in its own colour.
 *
 * **Companies simple-icons does not carry keep their initials chip** — Qorvo, Calterah, Spark,
 * Zigpos, HaiLa, Blind Creek Associates, Ultra-radio and the rest. `missing` below is that list,
 * and `feature-graph.test.ts` pins it so a new name shows up as a question rather than silently
 * falling back.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import docMeta from '../src/course/docMeta.json'

/** Pinned: a brand mark that changes under us would change the picture without a commit. */
const VERSION = '13.16.0'
const CDN = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`
const OUT = 'src/course/orgLogos.json'

/**
 * Affiliation name (as `docMeta.json` normalises it) → simple-icons slug.
 *
 * Only the companies that actually appear on a cited contribution are here; the map is hand-made
 * because a company's own spelling of itself is not its slug (「STMicroelectronics」 →
 * `stmicroelectronics`, but 「Blind Creek Associates」 → nothing at all).
 */
const SLUG: Record<string, string> = {
  Apple: 'apple',
  Cisco: 'cisco',
  Huawei: 'huawei',
  LG: 'lg',
  MediaTek: 'mediatek',
  Meta: 'meta',
  NXP: 'nxp',
  Qualcomm: 'qualcomm',
  Samsung: 'samsung',
  Sony: 'sony',
  STMicroelectronics: 'stmicroelectronics',
}

const curl = (url: string): string =>
  execFileSync('curl', ['-s', '--max-time', '60', url], { encoding: 'utf8', maxBuffer: 64e6 })

/** Every company named on a cited document, so the fallback list is measured, not guessed. */
const named = [...new Set(Object.values(docMeta.docs).flatMap((d) => d.orgs))].sort()

const data = JSON.parse(curl(`${CDN}/_data/simple-icons.json`)) as
  { icons: { title: string; hex: string; source: string }[] }
const hexOf = new Map(data.icons.map((i) => [i.title.toLowerCase(), i.hex]))

const logos: Record<string, { slug: string; hex: string; path: string }> = {}
const missing: string[] = []
for (const name of named) {
  const slug = SLUG[name]
  if (slug === undefined) { missing.push(name); continue }
  const svg = curl(`${CDN}/icons/${slug}.svg`)
  const path = /<path d="([^"]+)"/.exec(svg)?.[1]
  const title = /<title>([^<]+)<\/title>/.exec(svg)?.[1] ?? name
  if (path === undefined) { missing.push(name); continue }
  const hex = hexOf.get(title.toLowerCase()) ?? hexOf.get(slug) ?? '888888'
  logos[name] = { slug, hex: `#${hex}`, path }
  console.log(`  ${name.padEnd(20)} ${slug.padEnd(20)} #${hex}  ${path.length} chars`)
}

const out = {
  comment: `Generated by scripts/org-logos.ts from simple-icons ${VERSION} (CC0-1.0). Each entry is`
    + ' one 24x24 path and the brand hex. The marks are the property of their owners and are used'
    + ' here to identify the companies named on IEEE mentor contributions. Do not edit by hand.',
  generated: new Date().toISOString().slice(0, 10),
  source: `${CDN}/icons/<slug>.svg`,
  license: 'CC0-1.0 (simple-icons); the marks remain the trademarks of their owners',
  version: VERSION,
  /** Companies with no mark in simple-icons: the map draws their initials instead. */
  missing,
  logos,
}
const text = `${JSON.stringify(out, null, 1)}\n`

if (process.argv.includes('--check')) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const strip = (s: string): string => s.replace(/"generated": "[^"]+",/g, '')
  if (strip(have) !== strip(text)) {
    console.error(`${OUT} is stale — run: npx vite-node scripts/org-logos.ts`)
    process.exit(1)
  }
  console.log(`${OUT}: up to date (${Object.keys(logos).length} marks)`)
} else {
  writeFileSync(OUT, text)
  console.log(`→ ${OUT}: ${Object.keys(logos).length} marks, ${missing.length} without one`
    + ` (${missing.join(', ')})`)
}
